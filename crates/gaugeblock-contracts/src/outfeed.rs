//! `outfeed` release-plan and `suite.lock` wire domain.

use serde::{Deserialize, Serialize};

/// Conventional commit classification.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub enum ConventionalKind {
    /// New feature (`feat`).
    Feat,
    /// Bug fix (`fix`).
    Fix,
    /// Refactoring (`refactor`).
    Refactor,
    /// Performance enhancement (`perf`).
    Perf,
    /// Documentation (`docs`).
    Docs,
    /// Code style or formatting (`style`).
    Style,
    /// Chore or maintenance (`chore`).
    Chore,
    /// Continuous integration (`ci`).
    Ci,
    /// Build system or dependencies (`build`).
    Build,
    /// Test suite (`test`).
    Test,
    /// Any other conventional prefix.
    Other(String),
}

/// Parsed git commit metadata.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CommitInfo {
    /// Short or full git commit SHA.
    pub sha: String,
    /// Raw commit summary line.
    pub summary: String,
    /// Optional commit body.
    pub body: Option<String>,
    /// Conventional commit kind.
    pub kind: ConventionalKind,
    /// Optional scope (e.g. `outfeed-core`).
    pub scope: Option<String>,
    /// Whether the commit introduces a breaking API or contract change.
    pub is_breaking: bool,
    /// Breaking change description when present.
    pub breaking_description: Option<String>,
    /// Referenced Storypole ticket keys (e.g. `["GB-41", "GB-45"]`).
    pub referenced_tickets: Vec<String>,
}

/// SemVer bump classification.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub enum BumpType {
    /// Increments the major version (`1.0.0` -> `2.0.0`).
    Major,
    /// Increments the minor version (`0.1.0` -> `0.2.0`).
    Minor,
    /// Increments the patch version (`0.1.0` -> `0.1.1`).
    Patch,
    /// Increments the pre-release patch sequence (`0.1.0-beta.2` -> `0.1.0-beta.3`).
    PreReleasePatch,
    /// Increments the pre-release minor base (`0.1.0-beta.2` -> `0.2.0-beta.1`).
    PreReleaseMinor,
    /// Increments the pre-release alpha sequence (`0.1.0-alpha.2` -> `0.1.0-alpha.3`).
    PreReleaseAlpha,
}

/// In-memory diff representing a planned manifest edit.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ManifestDiff {
    /// File path relative to the repository root.
    pub relative_path: String,
    /// Existing content before the edit.
    pub original_content: String,
    /// Planned content after the edit.
    pub proposed_content: String,
}

/// Full release proposal generated by `outfeed`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ReleasePlan {
    /// Target repository name (e.g. `sawhorse`).
    pub repo_name: String,
    /// Existing version before the release.
    pub current_version: String,
    /// Proposed version after the release.
    pub target_version: String,
    /// Category of version bump.
    pub bump_type: BumpType,
    /// Justification for the selected bump.
    pub bump_rationale: String,
    /// Commits included in this release.
    pub commits: Vec<CommitInfo>,
    /// Storypole ticket keys shipped in this release.
    pub referenced_tickets: Vec<String>,
    /// Rendered Markdown section to append to `CHANGELOG.md`.
    pub changelog_markdown: String,
    /// Planned manifest modifications.
    pub manifest_diffs: Vec<ManifestDiff>,
}

/// Release status summary for a single repository.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct ReleaseStatus {
    /// Repository name.
    pub repo_name: String,
    /// Current manifest version.
    pub current_version: String,
    /// Latest release tag, when one exists.
    pub latest_tag: Option<String>,
    /// Number of unreleased commits since the latest tag.
    pub unreleased_commits: usize,
    /// Whether the working tree is clean.
    pub is_clean: bool,
}

/// Top-level metadata for `suite.lock`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SuiteMetadata {
    /// Meta-harness ecosystem release version.
    pub version: String,
    /// Timestamp of lockfile generation in UTC ISO 8601.
    pub created_at: String,
    /// Canonical organization or meta-harness name.
    pub meta_harness: String,
}

/// Pinned state for a member repository in `suite.lock`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SuiteToolEntry {
    /// Member repository name.
    pub name: String,
    /// Package version declared in the repository's root `Cargo.toml`.
    pub version: String,
    /// Exact git commit SHA currently checked out.
    pub commit: String,
    /// Most recent release tag, if present.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub tag: Option<String>,
}

/// Canonical schema for `suite.lock`.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct SuiteLock {
    /// Ecosystem release metadata.
    pub suite: SuiteMetadata,
    /// Pinned member tool snapshots.
    pub tools: Vec<SuiteToolEntry>,
}
